const { open, bayText, launch } = require('./lib.js');
const pick = (t) => t.split('\n').filter((l) => /^(Effort:|All-out|Courtesy ceiling|At this effort)/.test(l)).join(' | ');
const settle = async (page) => { for (let i = 0; i < 200; i++) { await page.waitForTimeout(250); if (!/working it out/i.test(await bayText(page))) return; } };
(async () => {
  const b = await launch();
  const st = JSON.parse(process.argv[2]), other = process.argv[3];
  let { page } = await open(b, st);
  await settle(page);
  console.log('fresh       :', pick(await bayText(page)));
  await page.close();
  ({ page } = await open(b, st, {}));
  const pend = /working it out/i.test(await bayText(page));
  await page.selectOption('#c-obj', other);
  await page.waitForTimeout(100);
  console.log('was pending at switch:', pend, '| new plan pending:', /working it out/i.test(await bayText(page)), '| after switch to', other, ':', pick(await bayText(page)));
  await page.waitForTimeout(15000);
  await page.selectOption('#c-obj', st.cObj);
  await settle(page);
  console.log('back again  :', pick(await bayText(page)));
  await b.close();
})();
