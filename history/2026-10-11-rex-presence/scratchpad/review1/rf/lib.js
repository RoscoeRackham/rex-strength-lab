global.window = global.window || {};
const RF = __dirname + '/'; const ROOT = process.env.HEAD ? RF + 'head/rex-strength-lab/' : RF + 'wt/';
const P = require(ROOT + 'src/engine.js');
require(ROOT + 'src/data.js');
const D = window.DINO_DATA;
const g = P.K.g;
const surf = (id) => D.surfaces.find((s) => s.id === id);
const obj = (id) => D.objects.find((o) => o.id === id);
const rex = () => P.makeBody({ build: 'rex', H: P.DEFAULT_BODIES.rex.H, m: P.DEFAULT_BODIES.rex.m });
const ollie = () => P.makeBody({ build: 'ollie', H: P.DEFAULT_BODIES.ollie.H, m: P.DEFAULT_BODIES.ollie.m });
const ctx = (o) => Object.assign({ F: 100 * 907.18474 * g, mode: 'comic', body: rex(), surface: surf('concrete'), groundHolds: false, anchor: 'friction', gentleHold: false, safePassenger: false, silentStrike: false, softLanding: false, coolFlight: false }, o || {});
module.exports = { P, D, g, surf, obj, rex, ollie, ctx };
