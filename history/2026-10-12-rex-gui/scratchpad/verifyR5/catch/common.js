global.window = {};
const P = require('/home/user/rex-strength-lab/rex-strength-lab/src/engine.js');
require('/home/user/rex-strength-lab/rex-strength-lab/src/data.js');
const D = window.DINO_DATA, K = P.K, g = K.g;
const obj = (id) => D.objects.find((x) => x.id === id);
const rex = P.makeBody({ build: 'rex', H: 3.048, m: 3007 }), ollie = P.makeBody({ build: 'ollie', H: 3.048, m: 3007 });
const conc = D.surfaces.find((s) => s.id === 'concrete');
const ON = { airAbsorb: 1, keepForm: true, unbreakable: true, ownRecoil: true };
const ctxOf = (F, extra) => Object.assign({ F, mode: 'comic', body: rex, surface: conc, anchor: 'friction' }, extra || {});
const leg = (kg, extra, oid, Dd, style, oExtra) => { const c = ctxOf(kg * g, extra); return P.catchLeg(c, Object.assign({}, c, { body: ollie }, oExtra || {}), obj(oid), Dd, style || 'hard'); };
const sig = (x, n) => (typeof x === 'number' ? Number(x.toPrecision(n || 4)) : x);
module.exports = { P, D, K, g, obj, rex, ollie, conc, ON, ctxOf, leg, sig };
