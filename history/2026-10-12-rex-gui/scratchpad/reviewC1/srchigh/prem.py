import math
G=6.67430e-11; a=6371e3
L=[(0,1221.5,[13.0885,0,-8.8381,0]),(1221.5,3480,[12.5815,-1.2638,-3.6426,-5.5281]),(3480,5701,[7.9565,-6.4761,5.5283,-3.0807]),
   (5701,5771,[5.3197,-1.4836,0,0]),(5771,5971,[11.2494,-8.0298,0,0]),(5971,6151,[7.1089,-3.8045,0,0]),(6151,6346.6,[2.6910,0.6924,0,0]),
   (6346.6,6356,[2.9,0,0,0]),(6356,6368,[2.6,0,0,0]),(6368,6371,[1.02,0,0,0])]
def rho(r):
    rk=r/1e3
    for lo,hi,c in L:
        if lo<=rk<=hi:
            x=r/a; return 1000*sum(ci*x**i for i,ci in enumerate(c))
n=400000; M=0; U=0; I=0
for i in range(n):
    r=(i+0.5)/n*a; dr=a/n; p=rho(r); dm=4*math.pi*r*r*p*dr
    Mmid=M+dm/2
    U+=G*Mmid*dm/r; M+=dm; I+=2/3*r*r*dm
print('M',M,'U',U,'I/MR2',I/(M*a*a))
